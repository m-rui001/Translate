# 与构建真源同步的镜像文件：同一批替换再落到 *translations.json
MIRRORS = {
    B / "egerton_zh.json": B / "egerton_translations.json",
    B / "second_zh.json": B / "second_translations.json",
}


def patch(path, pairs):
    text = path.read_text(encoding="utf-8", newline="")
    for old, new, why in pairs:
        assert old in text and text.count(old) == 1, (path.name, old, text.count(old))
        text = text.replace(old, new)
    path.write_text(text, encoding="utf-8", newline="")
    return len(pairs)


def main():
    total = 0
    for path, pairs in EDITS:
        bak = path.with_name(path.name + BAK)
        if not bak.exists():
            shutil.copy2(path, bak)
        n = patch(path, pairs)
        total += n
        target = MIRRORS.get(path)
        if target is not None:
            n2 = patch(target, pairs)
            assert n2 == n, (target.name, n2, n)
        print(f"{path.name}: {n} 条")
    print("合计", total, "条")


main()
