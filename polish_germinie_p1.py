def main():
    d = {}
    for rel, old, new, why in E:
        if why == 'noop-placeholder-remove':
            continue
        p = os.path.join(OUT, *rel.split('/'))
        if p not in d:
            d[p] = open(p, encoding='utf-8').read()
        t = d[p]
        n = t.count(old)
        assert n == 1, (rel, old, n)
        d[p] = t.replace(old, new)
    for p, t in d.items():
        bak = p + '.bak_20261125'
        if not os.path.exists(bak):
            shutil.copy2(p, bak)
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(t)
    print('files', len(d), 'edits', len([e for e in E if e[3] != 'noop-placeholder-remove']))

