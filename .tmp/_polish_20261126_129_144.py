CHUNKS = ['129', '131', '137', '139', '144']


def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def stat(t):
    norm = t.replace('\r\n', '\n')
    lines = norm.split('\n')
    return (len(lines), len([x for x in lines if x.strip()]),
            sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff'),
            'CRLF' if '\r\n' in t else 'LF')


def main():
    texts, before = {}, {}
    for c in CHUNKS:
        d = os.path.join(ROOT, 'chunk' + c)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copyfile(f, b)
            print('backup ->', b)
        else:
            print('backup exists, keep ->', b)
        texts[c] = load(f)
        before[c] = stat(texts[c])

    counts = {}
    for c, cat, old, new in EDITS:
        t = texts[c]
        assert old in t, (c, cat, old[:30])
        assert t.count(old) == 1, (c, cat, 'not unique', t.count(old))
        texts[c] = t.replace(old, new, 1)
        counts[c] = counts.get(c, 0) + 1
        print(f'chunk{c} [{cat}] ok  ...{new[-14:]}')

    for c in CHUNKS:
        d = os.path.join(ROOT, 'chunk' + c)
        save(os.path.join(d, 'final.txt'), texts[c])
        a, b = before[c], stat(texts[c])
        print(f'chunk{c}: 改动 {counts.get(c, 0)} 条 | 行数 {a[0]}->{b[0]} 段数 {a[1]}->{b[1]} '
              f'| 汉字 {a[2]}->{b[2]} | {a[3]}')
        assert a[0] == b[0] and a[1] == b[1] and a[3] == b[3], 'structural change!'

    ast.parse(open(__file__, encoding='utf-8').read())
    print('AST OK; 总改动', len(EDITS), '条')


if __name__ == '__main__':
    main()