def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    report = []
    for name, edits in EDITS.items():
        d = os.path.join(BASE, name)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
        with open(f, encoding='utf-8', newline='') as fh:
            text = fh.read()
        before = text
        n0_lines = len(text.replace('\r\n', '\n').split('\n'))
        n0_cjk = cjk(text)
        done = 0
        for old, new in edits:
            if old not in text:
                assert new in text, (name, old[:30])
                continue
            assert text.count(old) == 1, (name, old[:30], text.count(old))
            text = text.replace(old, new)
            done += 1
        with open(f, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        n1_lines = len(text.replace('\r\n', '\n').split('\n'))
        assert n0_lines == n1_lines, (name, n0_lines, n1_lines)
        assert text.count('\r\n') == before.count('\r\n')
        assert text.count('“') == text.count('”')
        assert '"' not in text
        assert text.count('⟦') == before.count('⟦')
        report.append(f'{name}: 改动 {done} 条, 行数 {n0_lines}->{n1_lines}, 汉字 {n0_cjk}->{cjk(text)}, '
                      f'CRLF {text.count(chr(13) + chr(10))}')
    print('\n'.join(report))


main()
