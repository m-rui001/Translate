def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def stats(t):
    norm = t.replace('\r\n', '\n')
    lines = norm.split('\n')
    return len(lines), sum(1 for x in lines if x.strip()), sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    by_chunk = {}
    for c, cat, old, new, why in EDITS:
        by_chunk.setdefault(c, []).append((cat, old, new, why))

    for c in sorted(by_chunk):
        d = os.path.join(BASE, 'chunk' + c)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
        text = load(f)
        lines0, paras0, cjk0 = stats(text)
        n = 0
        for cat, old, new, why in by_chunk[c]:
            assert old in text, (c, 'MISSING', old)
            assert text.count(old) == 1, (c, 'NOT UNIQUE', old, text.count(old))
            text = text.replace(old, new, 1)
            n += 1
        save(f, text)
        lines1, paras1, cjk1 = stats(text)
        assert (lines0, paras0) == (lines1, paras1), (c, 'STRUCTURE CHANGED')
        crlf = 'CRLF' if '\r\n' in text else 'LF'
        print(f'chunk{c}: 改动 {n} 条 | 行 {lines0}->{lines1} | 段 {paras0}->{paras1} | '
              f'汉字 {cjk0}->{cjk1} | {crlf}')


if __name__ == '__main__':
    main()

