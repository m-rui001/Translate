def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def stats(t):
    norm = t.replace('\r\n', '\n')
    lines = norm.split('\n')
    return (len(lines), len(t), t.count('\r\n'),
            len(re.findall(r'[\u4e00-\u9fff]', t)))


def main():
    total = 0
    for name in ('chunk186', 'chunk187', 'chunk188', 'chunk189', 'chunk191'):
        d = os.path.join(ROOT, name)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
            print(f'{name}: backup created')
        else:
            print(f'{name}: backup already exists, kept')
        text = load(f)
        before = stats(text)
        n = 0
        for cat, old, new in EDITS[name]:
            assert old in text, f'{name} NOT FOUND: {old[:40]}'
            assert text.count(old) == 1, f'{name} NOT UNIQUE: {old[:40]}'
            text = text.replace(old, new, 1)
            n += 1
            print(f'  {cat} {old[:26]}… -> {new[:26]}…')
        save(f, text)
        after = stats(text)
        assert before[0] == after[0], f'{name} line count changed'
        total += n
        print(f'{name}: edits={n} lines {before[0]}->{after[0]} '
              f'chars {before[1]}->{after[1]} han {before[3]}->{after[3]} '
              f'crlf {after[2]}')
    print(f'== total edits {total}')


main()
