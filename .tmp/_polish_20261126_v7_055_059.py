def han(s):
    return sum(1 for c in s if "\u4e00" <= c <= "\u9fff")


def main():
    total = 0
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, "chunk" + chunk)
        path = os.path.join(d, "final.txt")
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before_lines = text.count("\n") + 1
        before_han = han(text)
        crlf = "\r\n" in text
        n = 0
        for old, new in edits:
            assert old in text, "缺串: " + old[:30]
            assert text.count(old) == 1, "非唯一: " + old[:30]
            text = text.replace(old, new)
            n += 1
        assert text.count("\n") + 1 == before_lines, "行数变了"
        assert "\n\n\n" not in text, "出现空段"
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        with open(path, encoding="utf-8", newline="") as f:
            chk = f.read()
        assert chk == text
        print("chunk%s 改动 %d 条 | 行数 %d→%d | 汉字 %d→%d | %s"
              % (chunk, n, before_lines, chk.count("\n") + 1,
                 before_han, han(chk), "CRLF" if crlf else "LF"))
        total += n
    print("合计改动 %d 条" % total)


if __name__ == "__main__":
    main()

