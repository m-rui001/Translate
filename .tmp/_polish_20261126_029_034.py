def han_count(s):
    return len(re.findall(r"[\u4e00-\u9fff]", s))


def main():
    report = []
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        path = os.path.join(d, "final.txt")
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        nl = "\r\n" if "\r\n" in text else "\n"
        before_lines = text.count("\n")
        before_han = han_count(text)
        applied = 0
        seen = set()
        for old, new in edits:
            if old == new:
                continue
            if old in seen:
                continue
            seen.add(old)
            assert old in text, "NOT FOUND in %s: %r" % (chunk, old[:40])
            assert text.count(old) == 1, "NOT UNIQUE in %s: %r" % (chunk, old[:40])
            text = text.replace(old, new)
            applied += 1
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        with open(path, encoding="utf-8", newline="") as f:
            check = f.read()
        assert check == text
        after_lines = text.count("\n")
        after_han = han_count(text)
        assert before_lines == after_lines, "%s line count changed" % chunk
        assert ("\r\n" in text) == (nl == "\r\n"), "%s newline changed" % chunk
        report.append((chunk, applied, before_lines, after_lines, before_han, after_han,
                       "CRLF" if nl == "\r\n" else "LF"))
    print("chunk  edits  lines(b/a)  han(b/a)  nl")
    for r in report:
        print("%s   %2d   %d/%d   %d/%d   %s" % r)


if __name__ == "__main__":
    main()
