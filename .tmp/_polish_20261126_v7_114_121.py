def process(chunk, edits):
    d = os.path.join(BASE, chunk)
    f = os.path.join(d, 'final.txt')
    b = os.path.join(d, BAK)
    with open(f, encoding='utf-8', newline='') as fh:
        text = fh.read()
    before = text
    n = 0
    for (c, old, new, cat, why) in edits:
        assert old in text, (chunk, 'old not found', old[:30])
        assert text.count(old) == 1, (chunk, 'old not unique', old[:30])
        text = text.replace(old, new)
        n += 1
    if not os.path.exists(b):
        shutil.copyfile(f, b)
        made = '新建'
    else:
        made = '已存在（未覆盖）'
    with open(f, 'w', encoding='utf-8', newline='') as fh:
        fh.write(text)
    cjk = lambda s: sum(1 for ch in s if '\u4e00' <= ch <= '\u9fff')
    lines = lambda s: s.replace('\r\n', '\n').count('\n') + 1
    print('%s: 改动 %d 条 | 行数 %d→%d | 汉字 %d→%d | CRLF %d→%d | 备份 %s'
          % (chunk, n, lines(before), lines(text), cjk(before), cjk(text),
             before.count('\r\n'), text.count('\r\n'), made))
    return n, cat_counts(edits)


def cat_counts(edits):
    d = {}
    for e in edits:
        d[e[3]] = d.get(e[3], 0) + 1
    return d


def main():
    total = 0
    cats = {}
    for chunk in ('chunk114', 'chunk120', 'chunk121'):
        es = [e for e in EDITS if e[0] == chunk]
        n, cc = process(chunk, es)
        total += n
        for k, v in cc.items():
            cats[k] = cats.get(k, 0) + v
    print('合计 %d 条：%s' % (total, ' '.join('%s %d' % (k, cats[k]) for k in sorted(cats))))


