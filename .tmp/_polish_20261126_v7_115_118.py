def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


total = 0
for n, edits in EDITS.items():
    d = os.path.join(BASE, 'chunk%d' % n)
    fp = os.path.join(d, 'final.txt')
    bp = os.path.join(d, BAK)
    if not os.path.exists(bp):
        shutil.copyfile(fp, bp)
    text = load(fp)
    bak = load(bp)
    before_lines = len(text.replace('\r\n', '\n').split('\n'))
    before_cjk = cjk(text)
    for old, new in edits:
        assert old in text, (n, 'MISSING', old[:30])
        assert text.count(old) == 1, (n, 'NOT UNIQUE', old[:30])
        text = text.replace(old, new)
    assert len(text.replace('\r\n', '\n').split('\n')) == before_lines, n
    assert text.count('⟦') == bak.count('⟦'), n
    assert text.count('“') == text.count('”'), n
    save(fp, text)
    print('chunk%d: 改动 %d 条, 行数 %d -> %d, 汉字 %d -> %d, CRLF %s'
          % (n, len(edits), before_lines,
             len(text.replace('\r\n', '\n').split('\n')),
             before_cjk, cjk(text), text.count('\r\n')))
    total += len(edits)

print('合计改动', total, '条')
