def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def main():
    order, cur = [], None
    for c, k, old, new in EDITS:
        if c != cur:
            order.append(c)
            cur = c
    for chunk in order:
        d = os.path.join(BASE, 'chunk' + chunk)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)          # 备份已存在时绝不覆盖
        before = load(b)
        text = load(f)
        n = last = 0
        for c, k, old, new in EDITS:
            if c != chunk:
                continue
            assert text.count(old) == 1, (chunk, k, old, text.count(old))
            text = text.replace(old, new)
            n += 1
            last = k
        # 红线自查：段数 / 行数 / 空行结构 / 换行符类型不变
        for norm in (before, text):
            pass
        nb = before.replace('\r\n', '\n')
        nt = text.replace('\r\n', '\n')
        assert nb.count('\n') == nt.count('\n'), chunk + ' 行数变了'
        assert len([x for x in nb.split('\n') if x.strip()]) == len(
            [x for x in nt.split('\n') if x.strip()]), chunk + ' 段数变了'
        assert (before.count('\r\n') > 0) == (text.count('\r\n') > 0), chunk + ' 换行符类型变了'
        assert text.count('"') == 0, chunk + ' 出现 ASCII 引号'
        assert text.count('⟦') == before.count('⟦'), chunk + ' ⟦ 数变了'
        save(f, text)
        cjk_b = sum(1 for ch in before if '\u4e00' <= ch <= '\u9fff')
        cjk_a = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        print(f'chunk{chunk}: 改动 {n} 条  行数 {nb.count(chr(10))} -> {nt.count(chr(10))}  '
              f'汉字 {cjk_b} -> {cjk_a}  换行符 {"CRLF" if chr(13) in text else "LF"}  (末类 {last})')


