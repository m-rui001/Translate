def stats(txt):
    lines = txt.replace('\r\n', '\n').split('\n')
    return len(lines), sum(1 for x in lines if x.strip()), sum(1 for ch in txt if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for chunk, pairs in EDITS.items():
        path = os.path.join(BASE, chunk, 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        before = stats(text)
        for old, new in pairs:
            assert old in text, f'{chunk}: 未命中 {old[:24]}'
            assert text.count(old) == 1, f'{chunk}: 命中 {text.count(old)} 次 {old[:24]}'
            text = text.replace(old, new)
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        after = stats(text)
        assert before[0] == after[0] and before[1] == after[1], f'{chunk}: 行数/段数变动'
        total += len(pairs)
        print(f'{chunk}: 改动 {len(pairs)} 条 | 行 {before[0]}->{after[0]} | 段 {before[1]}->{after[1]} '
              f'| 汉字 {before[2]}->{after[2]}')
    print('total edits:', total)


main()
