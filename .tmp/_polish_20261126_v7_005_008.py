def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def apply_one(chunk):
    d = os.path.join(ROOT, chunk)
    f = os.path.join(d, 'final.txt')
    bak = os.path.join(d, BAK)
    # 从备份还原，保证脚本可重复执行（不覆盖备份本身）
    with open(bak, encoding='utf-8', newline='') as fh:
        text = fh.read()
    with open(f, 'w', encoding='utf-8', newline='') as fh:
        fh.write(text)
    before_lines = len(text.replace('\r\n', '\n').split('\n'))
    before_cjk = cjk(text)
    n = 0
    for old, new in EDITS[chunk]:
        assert old in text, (chunk, 'MISS', old[:30])
        assert text.count(old) == 1, (chunk, 'NOT UNIQUE', old[:30])
        text = text.replace(old, new)
        n += 1
    with open(f, 'w', encoding='utf-8', newline='') as fh:
        fh.write(text)
    after_lines = len(text.replace('\r\n', '\n').split('\n'))
    after_cjk = cjk(text)
    print('%s: 改动 %d 条 | 行数 %d->%d | 汉字 %d->%d | %s'
          % (chunk, n, before_lines, after_lines, before_cjk, after_cjk,
             'CRLF' if '\r\n' in text else 'LF'))
    assert before_lines == after_lines
    return n


