def main():
    total = 0
    report = []
    for piece, edits in EDITS.items():
        path = os.path.join(BASE, piece.replace('/', os.sep), 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        before_crlf = text.count('\r\n')
        before_lines = text.replace('\r\n', '\n').split('\n')
        before_paras = [x for x in before_lines if x.strip()]
        before_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')

        for old, new in edits:
            assert old in text, f'{piece}: MISSING {old[:30]}'
            assert text.count(old) == 1, f'{piece}: NOT UNIQUE {old[:30]}'
            text = text.replace(old, new)

        after_lines = text.replace('\r\n', '\n').split('\n')
        after_paras = [x for x in after_lines if x.strip()]
        assert len(before_lines) == len(after_lines), f'{piece}: 行数变了'
        assert len(before_paras) == len(after_paras), f'{piece}: 段数变了'
        assert text.count('\r\n') == before_crlf, f'{piece}: 换行符变了'
        assert text.count('“') == text.count('”'), f'{piece}: 引号不成对'

        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)

        after_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        total += len(edits)
        report.append((piece, len(edits), len(before_paras), len(before_lines),
                       before_cjk, after_cjk, before_crlf))

    print('改动条数：', total)
    for piece, n, paras, lines, c0, c1, crlf in report:
        print(f'{piece}: 改动 {n} 条 | 段 {paras} | 行 {lines} | 汉字 {c0}->{c1} | CRLF {crlf}')


main()
