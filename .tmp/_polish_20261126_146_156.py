def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    by_chunk = {}
    for chunk, cat, old, new in EDITS:
        by_chunk.setdefault(chunk, []).append((cat, old, new))

    for chunk in sorted(by_chunk):
        d = os.path.join(BASE, 'chunk' + chunk)
        path = os.path.join(d, 'final.txt')
        bak = os.path.join(d, BAK)
        if not os.path.exists(bak):
            shutil.copyfile(path, bak)
            made = 'created'
        else:
            made = 'kept'
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        before = (text.count('\n'), cjk(text), text.count('\r\n'))
        cats = []
        for cat, old, new in by_chunk[chunk]:
            assert old in text, (chunk, old)
            assert text.count(old) == 1, (chunk, text.count(old), old)
            text = text.replace(old, new)
            cats.append(cat)
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        after = (text.count('\n'), cjk(text), text.count('\r\n'))
        assert before[0] == after[0], (chunk, 'line count changed')
        print('chunk%s: bak %s | 改动 %d 条 %s | 行 %d->%d | 汉字 %d->%d | 换行 CRLF=%d'
              % (chunk, made, len(cats), ''.join(sorted(cats)), before[0], after[0],
                 before[1], after[1], after[2]))

    ast.parse(open(__file__, encoding='utf-8').read())
    print('self-check: ast.parse OK')


if __name__ == '__main__':
    main()