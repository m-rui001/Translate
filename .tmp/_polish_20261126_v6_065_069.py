def han(s):
    return sum(1 for c in s if "\u4e00" <= c <= "\u9fff")


report = []
for chunk, edits in EDITS.items():
    d = os.path.join(BASE, chunk)
    path = os.path.join(d, "final.txt")
    bak = path + ".bak_20261125"
    if not os.path.exists(bak):
        shutil.copy2(path, bak)
    with open(path, encoding="utf-8", newline="") as f:
        text = f.read()
    n_lines0, n_han0 = text.count("\n"), han(text)
    for old, new in edits:
        assert old in text, (chunk, old[:40])
        assert text.count(old) == 1, (chunk, "not unique", old[:40], text.count(old))
        text = text.replace(old, new, 1)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    report.append((chunk, len(edits), n_lines0, text.count("\n"), n_han0, han(text),
                   "CRLF" if "\r\n" in text else "LF"))

