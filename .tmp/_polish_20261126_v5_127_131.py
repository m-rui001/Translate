HAN = re.compile(r"[\u4e00-\u9fff]")


def stats(t):
    return len(t.split("\n")), len(HAN.findall(t))


def main():
    report = []
    for chunk, edits in EDITS.items():
        path = os.path.join(BASE, "chunk%s" % chunk, "final.txt")
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before = stats(text)
        n = 0
        for old, new in edits:
            assert old in text, (chunk, "MISSING", old[:40])
            assert text.count(old) == 1, (chunk, "NOT-UNIQUE", old[:40])
            text = text.replace(old, new)
            n += 1
        after = stats(text)
        assert before[0] == after[0], (chunk, "LINE-COUNT-CHANGED", before, after)
        assert text.count("\r\n") == before[0] - 1 if before[0] > 1 else True
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        report.append((chunk, before, after, n))

    print("%-6s %-14s %-14s %s" % ("chunk", "行/汉字(改前)", "行/汉字(改后)", "改动"))
    total = 0
    for chunk, before, after, n in report:
        total += n
        print("%-6s %-14s %-14s %d" % (chunk, "%d/%d" % before, "%d/%d" % after, n))
    print("合计改动", total, "条")


main()
