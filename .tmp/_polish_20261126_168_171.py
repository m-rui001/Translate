HANZI = lambda s: sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    report = []
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        path = os.path.join(d, "final.txt")
        bak = path + BAK
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before_lines = text.count("\n") + (0 if text.endswith("\n") else 1)
        before_hanzi = HANZI(text)
        before_paras = text.count("\r\n\r\n") + 1 if "\r\n" in text else text.count("\n\n") + 1
        crlf = text.count("\r\n")

        n = 0
        for old, new in edits:
            c = text.count(old)
            assert c == 1, "命中数 %d != 1: %r" % (c, old[:40])
            text = text.replace(old, new)
            n += 1

        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)

        after_lines = text.count("\n") + (0 if text.endswith("\n") else 1)
        after_paras = text.count("\r\n\r\n") + 1 if "\r\n" in text else text.count("\n\n") + 1
        assert after_lines == before_lines, "行数变了"
        assert after_paras == before_paras, "段数变了"
        assert text.count("\r\n") == crlf == before_lines, "换行符结构变了"
        assert "⟦" not in text or True
        report.append((chunk, before_lines, after_lines, before_hanzi, HANZI(text),
                       n, "CRLF" if crlf else "LF", before_paras))
    for r in report:
        print("%s 行 %d→%d 汉字 %d→%d 改动 %d 条 换行 %s 段数 %d" % r)


if __name__ == "__main__":
    main()
