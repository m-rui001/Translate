def han(s):
    return len(re.findall(r'[\u4e00-\u9fff]', s))


def run_chunk(chunk, edits):
    path = os.path.join(BASE, chunk, 'final.txt')
    bak = os.path.join(BASE, chunk, BAK)
    text = open(path, encoding='utf-8', newline='').read()
    before_lines = text.count('\n')
    before_han = han(text)
    if not os.path.exists(bak):
        shutil.copy2(path, bak)
    n = 0
    for cat, old, new, why in edits:
        assert old in text, (chunk, cat, old[:40])
        assert text.count(old) == 1, (chunk, cat, 'not unique', old[:40])
        text = text.replace(old, new)
        n += 1
    open(path, 'w', encoding='utf-8', newline='').write(text)

    check = open(path, encoding='utf-8', newline='').read()
    after_lines = check.count('\n')
    assert after_lines == before_lines, (chunk, before_lines, after_lines)
    paras = [p for p in check.replace('\r\n', '\n').split('\n') if p.strip()]
    assert all(p.strip() for p in paras)
    assert '⟦' not in new  # safeguard: no marker touched
    assert check.count('“') == check.count('”'), chunk
    assert '"' not in check
    print('%s: 改动 %d 条 | 行数 %d→%d | 汉字 %d→%d | 换行符 %s'
          % (chunk, n, before_lines, after_lines, before_han, han(check),
             'CRLF' if '\r\n' in check else 'LF'))
    return n, before_lines, after_lines, before_han, han(check)


