def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for n in sorted(EDITS):
        d = os.path.join(BASE, 'chunk%d' % n)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copyfile(f, b)
        text = load(f)
        before_lines = len(text.replace('\r\n', '\n').split('\n'))
        before_cjk = cjk(text)
        cnt = 0
        for old, new in EDITS[n]:
            if old not in text and new in text:
                continue  # 已应用过（脚本可重入）
            assert old in text, 'MISS %d: %s' % (n, old[:24])
            assert text.count(old) == 1, 'DUP %d: %s' % (n, old[:24])
            text = text.replace(old, new)
            cnt += 1
        save(f, text)
        after = load(f)
        assert len(after.replace('\r\n', '\n').split('\n')) == before_lines, 'LINECOUNT %d' % n
        assert after.count('\r\n') == text.count('\r\n')
        print('chunk%d: 改动 %d 条 | 行数 %d->%d | 汉字 %d->%d | crlf %d'
              % (n, cnt, before_lines,
                 len(after.replace('\r\n', '\n').split('\n')), before_cjk, cjk(after),
                 after.count('\r\n')))
        total += cnt
    print('总计改动 %d 条' % total)


main()
