CHUNKS = ["042", "044", "045", "047", "048"]


def hanzi(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    texts = {}
    for c in CHUNKS:
        p = os.path.join(BASE, "chunk%s" % c, "final.txt")
        with open(p, encoding="utf-8", newline="") as f:
            texts[c] = f.read()

    # 断言：每处 old 在对应文件中唯一
    for c, cat, old, new in EDITS:
        t = texts[c]
        n = t.count(old)
        assert n == 1, "chunk%s [%s] 命中 %d 次：%r" % (c, cat, n, old)
        assert old != new
        # 替换后不得引入半角标点/ASCII 引号
        assert not any(ch in new for ch in '"\'') or any(ch in old for ch in '"\'')
    print("断言通过：%d 处改动，全部唯一命中。" % len(EDITS))

    stats = []
    for c in CHUNKS:
        t0 = texts[c]
        t = t0
        cnt = 0
        for cc, cat, old, new in EDITS:
            if cc != c:
                continue
            t = t.replace(old, new, 1)
            cnt += 1
        nl = "CRLF" if "\r\n" in t0 else "LF"
        l0 = t0.replace("\r\n", "\n").count("\n")
        l1 = t.replace("\r\n", "\n").count("\n")
        assert l0 == l1, "chunk%s 行数变化 %d→%d" % (c, l0, l1)
        # 空段结构不变
        b0 = [x for x in t0.replace("\r\n", "\n").split("\n") if not x.strip()]
        b1 = [x for x in t.replace("\r\n", "\n").split("\n") if not x.strip()]
        assert len(b0) == len(b1), "chunk%s 空行数变化" % c
        assert t.count("⟦") == t0.count("⟦") and t.count("⟧") == t0.count("⟧")
        stats.append((c, l0, l1, hanzi(t0), hanzi(t), cnt, nl))

        if not DRY:
            p = os.path.join(BASE, "chunk%s" % c, "final.txt")
            with open(p, "w", encoding="utf-8", newline="") as f:
                f.write(t)

    print("%-6s %-9s %-13s %-4s %-5s" % ("chunk", "行数", "汉字", "改动", "换行"))
    for c, l0, l1, h0, h1, cnt, nl in stats:
        print("%-6s %d=%-7d %d→%-9d %-4d %-5s" % (c, l0, l1, h0, h1, cnt, nl))
    print("合计 %d 处：①%d ②%d ③%d ④%d ⑤%d ⑥%d ⑦%d" % (
        len(EDITS),
        sum(1 for e in EDITS if e[1] == "①"),
        sum(1 for e in EDITS if e[1] == "②"),
        sum(1 for e in EDITS if e[1] == "③"),
        sum(1 for e in EDITS if e[1] == "④"),
        sum(1 for e in EDITS if e[1] == "⑤"),
        sum(1 for e in EDITS if e[1] == "⑥"),
        sum(1 for e in EDITS if e[1] == "⑦"),
    ))
    print("DRY RUN，未落盘。" if DRY else "已落盘。")


main()
