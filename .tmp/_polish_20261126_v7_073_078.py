def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def dump(p, text):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(text)


def stats(txt):
    norm = txt.replace('\r\n', '\n')
    lines = norm.split('\n')
    crlf = txt.count('\r\n')
    cjk = sum(1 for ch in txt if '\u4e00' <= ch <= '\u9fff')
    return len(lines), sum(1 for x in lines if x.strip()), crlf, cjk


def main():
    order = []
    by_chunk = {}
    for chunk, cat, old, new, why in EDITS:
        if chunk not in by_chunk:
            by_chunk[chunk] = []
            order.append(chunk)
        by_chunk[chunk].append((cat, old, new, why))

    for chunk in order:
        d = os.path.join(BASE, chunk)
        f = os.path.join(d, 'final.txt')
        bak = os.path.join(d, BAK)
        if not os.path.exists(bak):
            shutil.copy2(f, bak)
        text = load(f)
        l0, p0, crlf0, cjk0 = stats(text)
        n = 0
        for cat, old, new, why in by_chunk[chunk]:
            assert old in text, (chunk, cat, old[:30])
            assert text.count(old) == 1, (chunk, cat, 'not unique', old[:30])
            text = text.replace(old, new)
            n += 1
        dump(f, text)
        l1, p1, crlf1, cjk1 = stats(text)
        assert (l0, p0, crlf0) == (l1, p1, crlf1), (chunk, 'structure changed')
        print(f'{chunk}: 改动 {n} 条 | 行 {l0}->{l1} 段 {p0}->{p1} '
              f'CRLF {crlf0}->{crlf1} 汉字 {cjk0}->{cjk1}')
    print('总改动', sum(len(v) for v in by_chunk.values()), '条')


main()
