HAN = lambda s: sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")

report = []
for chunk, pairs in EDITS.items():
    path = os.path.join(ROOT, "chunk" + chunk, "final.txt")
    with open(path, encoding="utf-8", newline="") as f:
        text = f.read()
    before = text
    nl = "CRLF" if "\r\n" in text else "LF"
    lines_before = text.count("\n") + 1
    han_before = HAN(text)
    for old, new in pairs:
        assert text.count(old) == 1, (chunk, old[:20], text.count(old))
        text = text.replace(old, new)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    # 结构校验：段数、空行数、换行符不变
    assert (text.count("\n") + 1) == lines_before
    assert text.count("\n\n") == before.count("\n\n")
    assert ("\r\n" in text) == ("\r\n" in before)
    report.append((chunk, len(pairs), lines_before, text.count("\n") + 1,
                   han_before, HAN(text), nl))

for r in report:
    print("chunk%s 改动%d条 | 行数 %d->%d | 汉字 %d->%d | %s"
          % (r[0], r[1], r[2], r[3], r[4], r[5], r[6]))

