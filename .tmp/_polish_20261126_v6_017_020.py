CHUNKS = ['017', '018', '019', '020']

# 允许批量替换的专名条目（同形多处）
MULTI = {(u'图兰', u'图赖讷'): 4}


def main():
    stats = {}
    for ch in CHUNKS:
        path = os.path.join(BASE, 'chunk' + ch, 'final.txt')
        with io.open(path, 'r', encoding='utf-8', newline='') as f:
            text = f.read()
        orig = text
        before_lines = text.count('\n')
        before_hz = hanzi(text)
        n = 0
        cats = []
        for c, cat, old, new, why in EDITS:
            if c != ch:
                continue
            if old == new:
                raise SystemExit('no-op edit %s %s' % (ch, cat))
            cnt = text.count(old)
            if (old, new) in MULTI:
                assert cnt == MULTI[(old, new)], (ch, old, cnt)
                text = text.replace(old, new)
                print('  [%s] %s x%d  %s -> %s' % (ch, cat, cnt, old, new))
                n += cnt
                cats.append(cat)
                continue
            assert cnt == 1, (ch, cat, old, cnt)
            text = text.replace(old, new)
            print('  [%s] %s  %s -> %s\n      理由: %s' % (ch, cat, old, new, why))
            n += 1
            cats.append(cat)
        # 结构校验：行数/空行不变，引号成对，无半角标点/⟦⟧
        assert text.count('\n') == before_lines, 'line count changed'
        assert text.count(u'“') == text.count(u'”'), 'quote mismatch'
        assert u'\u3000' not in text
        assert '⟦' not in text
        if text != orig:
            with io.open(path, 'w', encoding='utf-8', newline='') as f:
                f.write(text)
            print('  -> written %s' % path)
        stats[ch] = (before_lines, text.count('\n'), before_hz, hanzi(text), n, cats)

    print('\n=== 汇总 ===')
    total = 0
    for ch in CHUNKS:
        bl, al, bh, ah, n, cats = stats[ch]
        total += n
        cnt = {}
        for c in cats:
            cnt[c] = cnt.get(c, 0) + 1
        print('chunk%s 行 %d=%d 汉字 %d->%d 改动 %d %s' % (ch, bl, al, bh, ah, n, cnt))
    print('合计改动 %d 条' % total)


main()
