def han_count(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    total = 0
    for name, pairs in EDITS.items():
        path = os.path.join(BASE, name, "final.txt")
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
            bak_note = "新建备份"
        else:
            bak_note = "备份已存在，未覆盖"
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before_lines = text.count("\n")
        before_han = han_count(text)
        crlf = "\r\n" in text
        for old, new in pairs:
            assert old in text, (name, old[:30])
            assert text.count(old) == 1, (name, old[:30])
            text = text.replace(old, new)
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        after_lines = text.count("\n")
        assert before_lines == after_lines, (name, before_lines, after_lines)
        assert text.count("\r\n") == before_lines if crlf else True
        total += len(pairs)
        print(
            f"{name}: 改动 {len(pairs)} 条 | 行数 {before_lines}→{after_lines} | "
            f"汉字 {before_han}→{han_count(text)} | {'CRLF' if crlf else 'LF'} | {bak_note}"
        )
    print("总改动", total, "条")


main()
