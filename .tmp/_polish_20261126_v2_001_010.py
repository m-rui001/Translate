def cjk(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        fp = os.path.join(d, 'final.txt')
        bp = os.path.join(d, BAK)
        with open(fp, encoding='utf-8', newline='') as f:
            text = f.read()
        if not os.path.exists(bp):
            shutil.copy2(fp, bp)
        n0, c0 = len(text.split('\n')), cjk(text)
        for old, new in edits:
            assert old in text, (chunk, old)
            assert text.count(old) == 1, (chunk, old)
            text = text.replace(old, new)
        with open(fp, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        with open(fp, encoding='utf-8', newline='') as f:
            chk = f.read()
        n1, c1 = len(chk.split('\n')), cjk(chk)
        assert n0 == n1, (chunk, n0, n1)
        print(f'{chunk}: 改动 {len(edits)} 条  行数 {n0}->{n1}  汉字 {c0}->{c1}  '
              f'CRLF={chk.count(chr(13) + chr(10))}')


if __name__ == '__main__':
    main()
    ast.parse(open(__file__, encoding='utf-8').read())
