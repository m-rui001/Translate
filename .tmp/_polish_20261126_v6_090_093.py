def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, t):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)


def main():
    fail = 0
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
        txt = load(f)
        before_lines = txt.replace('\r\n', '\n').split('\n')
        before_paras = len([x for x in before_lines if x.strip()])
        before_cjk = sum(1 for ch in txt if '\u4e00' <= ch <= '\u9fff')
        crlf = '\r\n' in txt
        n = 0
        for old, new, cat, why in edits:
            if txt.count(old) != 1:
                print(f'!! {chunk} [{cat}] 命中 {txt.count(old)} 次: {old[:30]}...')
                fail += 1
                continue
            txt = txt.replace(old, new)
            n += 1
        save(f, txt)  # 每改完一个 chunk 立即落盘
        after_lines = txt.replace('\r\n', '\n').split('\n')
        after_paras = len([x for x in after_lines if x.strip()])
        after_cjk = sum(1 for ch in txt if '\u4e00' <= ch <= '\u9fff')
        quotes = {ch: txt.count(ch) for ch in '“”‘’'}
        print(f'{chunk}: {n}/{len(edits)} 条  lines {len(before_lines)}->{len(after_lines)}  '
              f'paras {before_paras}->{after_paras}  cjk {before_cjk}->{after_cjk}  '
              f'{"CRLF" if crlf else "LF"}  quotes {quotes}')
        assert len(before_lines) == len(after_lines)
        assert before_paras == after_paras
        assert ('\r\n' in txt) == crlf
        assert txt.count('“') == txt.count('”'), '双引号不成对'
        assert '‘' not in txt.replace('‘边’', ''), '残留单引号'
    print('---', 'ALL EDITS OK' if not fail else f'{fail} edit(s) MISSED')
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main())

