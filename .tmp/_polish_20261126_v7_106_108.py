HAN = re.compile(r'[\u4e00-\u9fff]')


def load(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def save(p, s):
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(s)


def main():
    total = 0
    for n, edits in sorted(EDITS.items()):
        d = os.path.join(BASE, 'chunk%03d' % n)
        fp = os.path.join(d, 'final.txt')
        bak = os.path.join(d, BAK)
        if not os.path.exists(bak):
            shutil.copyfile(fp, bak)
        text = load(fp)
        bak_text = load(bak)
        before_lines = text.replace('\r\n', '\n').split('\n')
        han_before = len(HAN.findall(text))
        done = 0
        for old, new in edits:
            assert text.count(old) == 1, ('命中数异常', n, old[:24], text.count(old))
            text = text.replace(old, new)
            done += 1
        after_lines = text.replace('\r\n', '\n').split('\n')
        assert len(before_lines) == len(after_lines), (n, '行数变了')
        assert [bool(x.strip()) for x in before_lines] == [bool(x.strip()) for x in after_lines], (n, '空行结构变了')
        assert text.count('\r\n') == bak_text.count('\r\n'), (n, '换行符变了')
        assert text.count('"') == 0 and text.count('⟦') == bak_text.count('⟦')
        save(fp, text)
        total += done
        print('chunk%03d: 改动 %d 条 / 行数 %d→%d / 汉字 %d→%d / %s'
              % (n, done, len(before_lines), len(after_lines), han_before,
                 len(HAN.findall(text)), 'CRLF' if '\r\n' in text else 'LF'))
    print('合计改动 %d 条' % total)


ast.parse(open(__file__, encoding='utf-8').read())
if __name__ == '__main__':
    main()