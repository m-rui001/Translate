def cjk(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    report = []
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        path = os.path.join(d, "final.txt")
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
            print("backup created:", bak)

        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        crlf = "\r\n" in text
        before_lines = text.count("\n")
        before_cjk = cjk(text)
        n = 0
        for old, new in edits:
            o = old.replace("\n", "\r\n") if crlf else old
            nw = new.replace("\n", "\r\n") if crlf else new
            assert o in text, "NOT FOUND in %s: %r" % (chunk, old[:40])
            assert text.count(o) == 1, "NOT UNIQUE in %s: %r" % (chunk, old[:40])
            text = text.replace(o, nw)
            n += 1
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)

        after = open(path, encoding="utf-8", newline="").read()
        after_lines = after.count("\n")
        assert after_lines == before_lines, (chunk, before_lines, after_lines)
        norm = after.replace("\r\n", "\n").strip("\n").split("\n")
        assert all(l.strip() for l in norm[::2]), chunk
        assert all(not l.strip() for l in norm[1::2]), chunk
        assert after.count("“") == after.count("”"), (chunk, after.count("“"), after.count("”"))
        report.append((chunk, before_lines, after_lines, before_cjk, cjk(after),
                       n, "CRLF" if crlf else "LF"))
    print("%-9s %-12s %-13s %-6s %s" % ("chunk", "lines", "cjk", "edits", "eol"))
    for r in report:
        print("%-9s %d->%d      %d->%d   %d     %s" % (r[0], r[1], r[2], r[3], r[4], r[5], r[6]))
    print("total edits:", sum(r[5] for r in report))


ast.parse(open(__file__, encoding="utf-8").read())
main()