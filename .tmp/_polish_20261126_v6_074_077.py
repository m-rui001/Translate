def cjk(s):
    return sum(1 for ch in s if '\u4e00' <= ch <= '\u9fff')


def main():
    for chunk, edits in EDITS.items():
        d = os.path.join(OUT, 'chunk' + chunk)
        path = os.path.join(d, 'final.txt')
        bak = path + '.bak_20261125'
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        crlf = '\r\n' in text
        lines_before = text.count('\n')
        cjk_before = cjk(text)
        applied = 0
        for old, new in edits:
            if old not in text:          # 二次运行时已施加过
                assert new in text, '既无旧串也无新串：' + old[:30]
                continue
            assert text.count(old) == 1, '命中多次：' + old[:30]
            assert new not in text, '已施加过：' + new[:30]
            text = text.replace(old, new)
            applied += 1
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        lines_after = text.count('\n')
        assert lines_before == lines_after, '行数变化'
        print('chunk%s: 改动 %d 条 | 行数 %d=%d | 汉字 %d→%d | 换行 %s'
              % (chunk, applied, lines_before, lines_after, cjk_before, cjk(text),
                 'CRLF' if crlf else 'LF'))


ast.parse(open(__file__, encoding='utf-8').read())
if __name__ == '__main__':
    main()