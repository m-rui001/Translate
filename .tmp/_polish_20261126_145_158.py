CATS = ["①", "②", "③", "④", "⑤", "⑥", "⑦"]


def hanzi(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    dry = "--dry" in sys.argv
    texts = {}
    for c in CHUNKS:
        p = os.path.join(BASE, c, "final.txt")
        with open(p, encoding="utf-8", newline="") as f:
            texts[c] = f.read()

    before = {c: (texts[c].count("\n"), hanzi(texts[c])) for c in CHUNKS}

    # 1) 断言所有 old 唯一命中
    bad = 0
    for c, cat, old, new in EDITS:
        n = texts[c].count(old)
        if n != 1:
            print("!! 命中数 %d（应为1）：[%s] %s" % (n, c, old[:40]))
            bad += 1
        if "\n" in old or "\r" in old:
            print("!! 跨行 old：[%s] %s" % (c, old[:30]))
            bad += 1
    if bad:
        print("断言失败 %d 处，中止。" % bad)
        raise SystemExit(1)
    print("断言通过：%d 处 old 均唯一命中。" % len(EDITS))

    if dry:
        for c in CHUNKS:
            print("%s dry-ok 行数 %d 汉字 %d" % (c, before[c][0], before[c][1]))
        return

    # 2) 备份（已存在不覆盖）
    for c in CHUNKS:
        src = os.path.join(BASE, c, "final.txt")
        bak = src + ".bak_20261125"
        if os.path.exists(bak):
            print("备份已存在，未覆盖：%s" % bak)
        else:
            shutil.copyfile(src, bak)
            print("新建备份：%s" % bak)

    # 3) 落盘
    for c in CHUNKS:
        p = os.path.join(BASE, c, "final.txt")
        text = texts[c]
        cnt = 0
        for cc, cat, old, new in EDITS:
            if cc != c:
                continue
            assert text.count(old) == 1, (c, old)
            text = text.replace(old, new)
            cnt += 1
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        lines, hz = text.count("\n"), hanzi(text)
        bl, bh = before[c]
        print("%s 改动 %2d 条  行数 %d=%d %s  汉字 %d→%d  换行 %s"
              % (c, cnt, bl, lines, "OK" if bl == lines else "!!变",
                 bh, hz, "CRLF" if "\r\n" in text else "LF"))

    # 4) 分类统计
    from collections import Counter
    stat = Counter()
    for c, cat, old, new in EDITS:
        for ch in cat:
            if ch in CATS:
                stat[ch] += 1
    print("总计 %d 条：" % len(EDITS)
          + " ".join("%s x%d" % (k, stat[k]) for k in CATS if stat[k]))


if __name__ == "__main__":
    main()
