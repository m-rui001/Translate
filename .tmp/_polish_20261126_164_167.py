def main():
    only = sys.argv[1:] or sorted(EDITS)
    report = []
    for ck in only:
        path = os.path.join(BASE, 'chunk%s' % ck, 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        before_han = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        before_lines = text.count('\n')
        n = 0
        for old, new in EDITS[ck]:
            assert old in text, (ck, 'NOT FOUND', old[:40])
            assert text.count(old) == 1, (ck, 'NOT UNIQUE', old[:40])
            assert new not in text, (ck, 'NEW ALREADY', new[:40])
            text = text.replace(old, new)
            n += 1
        after_han = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        after_lines = text.count('\n')
        assert before_lines == after_lines, (ck, 'LINECOUNT', before_lines, after_lines)
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        report.append((ck, n, before_lines, after_lines, before_han, after_han,
                       'CRLF' if '\r\n' in text else 'LF'))
    print('chunk  改动  行数前/后  汉字前/后  换行符')
    for r in report:
        print('%s   %3d   %d/%d   %d/%d   %s' % r)


main()
