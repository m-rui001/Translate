def main():
    total = 0
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
            print(f'{chunk}: backup created')
        else:
            print(f'{chunk}: backup exists, kept')
        with open(f, encoding='utf-8', newline='') as fh:
            text = fh.read()
        before = text
        n = 0
        for old, new in edits:
            if text.count(old) == 1:
                text = text.replace(old, new)
                n += 1
            elif text.count(new) == 1:
                continue  # 幂等：第二遍跑时已落盘，跳过
            else:
                raise AssertionError((chunk, old[:30], text.count(old)))
        if text != before:
            with open(f, 'w', encoding='utf-8', newline='') as fh:
                fh.write(text)
        norm = text.replace('\r\n', '\n')
        lines = norm.split('\n')
        paras = [x for x in lines if x.strip()]
        cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        print(f'{chunk}: {n} edits, lines {len(lines)}, paras {len(paras)}, '
              f'cjk {cjk}, CRLF={text.count(chr(13) + chr(10))}')
        total += n
    print('total edits:', total)


if __name__ == '__main__':
    main()
