def main():
    total = 0
    for piece, edits in EDITS.items():
        path = os.path.join(OUT, piece, 'final.txt')
        with open(path, encoding='utf-8', newline='') as fh:
            text = fh.read()
        nl = '\r\n' if '\r\n' in text else '\n'
        before_paras = len([x for x in text.replace('\r\n', '\n').split('\n') if x.strip()])
        before_lines = text.count('\n')
        before_hz = len(re.findall(r'[\u4e00-\u9fff]', text))
        n = 0
        for old, new in edits:
            old_n = old.replace('\n', nl)
            new_n = new.replace('\n', nl)
            assert text.count(old_n) == 1, ('命中数不为 1', piece, old_n[:40], text.count(old_n))
            text = text.replace(old_n, new_n)
            n += 1
        with open(path, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        after_paras = len([x for x in text.replace('\r\n', '\n').split('\n') if x.strip()])
        after_lines = text.count('\n')
        after_hz = len(re.findall(r'[\u4e00-\u9fff]', text))
        assert before_paras == after_paras, (piece, before_paras, after_paras)
        assert before_lines == after_lines, (piece, before_lines, after_lines)
        print('%s: 改动 %d 条 | 段数 %d==%d | 行数 %d==%d | 汉字 %d->%d | 换行 %s'
              % (piece, n, before_paras, after_paras, before_lines, after_lines,
                 before_hz, after_hz, 'CRLF' if nl == '\r\n' else 'LF'))
        total += n
    print('合计改动 %d 条' % total)
    return 0


if __name__ == '__main__':
    sys.exit(main())

