def han(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for name, edits in EDITS.items():
        d = os.path.join(BASE, name)
        f = os.path.join(d, 'final.txt')
        bak = os.path.join(d, BAK)
        with open(f, encoding='utf-8', newline='') as fh:
            text = fh.read()
        before_lines = text.count('\n')
        before_han = han(text)
        if not os.path.exists(bak):
            shutil.copy2(f, bak)
        new = text
        applied = skipped = 0
        for cat, old, rep, _note in edits:
            if new.count(old) == 0 and new.count(rep) >= 1:  # 幂等：已改过就跳过
                skipped += 1
                continue
            assert new.count(old) == 1, (name, cat, old, new.count(old))
            new = new.replace(old, rep)
            applied += 1
        assert new.count('\n') == before_lines, (name, 'line count changed')
        with open(f, encoding='utf-8', newline='') as fh:
            assert fh.read() == text
        with open(f, 'w', encoding='utf-8', newline='') as fh:
            fh.write(new)
        nl = 'CRLF' if '\r\n' in new else 'LF'
        print(f'{name}: 改动 {applied} 条（已落盘跳过 {skipped}） | 行数 {before_lines}->{new.count(chr(10))} | '
              f'汉字 {before_han}->{han(new)} | {nl}')
        total += applied
    print('total edits', total)
    for name, edits in EDITS.items():
        print(name, {c: sum(1 for e in edits if e[0] == c) for c in '①②③④⑤⑥⑦'
                     if any(e[0] == c for e in edits)})


main()
