def han(t):
    return sum(1 for ch in t if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for ck, pairs in EDITS.items():
        d = os.path.join('E:/Translate/work_proust/out/v4', f'chunk{ck}')
        fp = os.path.join(d, 'final.txt')
        bp = os.path.join(d, BAK)
        if not os.path.exists(bp):
            shutil.copyfile(fp, bp)
        with open(fp, encoding='utf-8', newline='') as f:
            text = f.read()
        before_lines = len(text.replace('\r\n', '\n').split('\n'))
        before_han = han(text)
        crlf = text.count('\r\n')
        for old, new in pairs:
            assert old in text, f'{ck}: MISSING {old[:30]}'
            assert text.count(old) == 1, f'{ck}: NOT UNIQUE {old[:30]}'
            text = text.replace(old, new, 1)
        assert len(text.replace('\r\n', '\n').split('\n')) == before_lines, f'{ck}: line count changed'
        assert text.count('\r\n') == crlf, f'{ck}: newline style changed'
        with open(fp, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        total += len(pairs)
        print(f'chunk{ck}: 改动 {len(pairs)} 条  行数 {before_lines}->{before_lines}  '
              f'汉字 {before_han}->{han(text)}  换行符 {"CRLF" if crlf else "LF"}')
    print('TOTAL', total)


main()
