def main():
    for cid, pairs in EDITS.items():
        p = os.path.join(BASE, 'chunk' + cid, 'final.txt')
        with open(p, encoding='utf-8', newline='') as f:
            text = f.read()
        cjk_before = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        lines_before = text.replace('\r\n', '\n').split('\n')
        for old, new in pairs:
            assert old in text, (cid, old[:24])
            assert text.count(old) == 1, (cid, old[:24])
            text = text.replace(old, new)
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        cjk_after = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        lines_after = text.replace('\r\n', '\n').split('\n')
        print(f'chunk{cid}: 改动 {len(pairs)} 条 | 行数 {len(lines_before)}->{len(lines_after)} | '
              f'汉字 {cjk_before}->{cjk_after} | crlf {text.count(chr(13) + chr(10))}')


main()
