def main():
    for chunk, edits in EDITS.items():
        d = os.path.join(ROOT, chunk)
        fp = os.path.join(d, 'final.txt')
        bp = os.path.join(d, BAK)
        if not os.path.exists(bp):
            shutil.copy2(fp, bp)
            print(f'{chunk}: backup created')
        else:
            print(f'{chunk}: backup already exists, kept')
        src = bp if FROM_BAK else fp
        with open(src, encoding='utf-8', newline='') as f:
            text = f.read()
        before_lines = text.count('\n')
        before_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        for old, new in edits:
            assert old in text, f'{chunk}: NOT FOUND -> {old[:40]}'
            assert text.count(old) == 1, f'{chunk}: NOT UNIQUE -> {old[:40]}'
            text = text.replace(old, new)
        assert text.count('\n') == before_lines, f'{chunk}: line count changed'
        with open(fp, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        after_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        print(f'{chunk}: edits {len(edits)}  lines {before_lines}->{text.count(chr(10))}  '
              f'cjk {before_cjk}->{after_cjk}  crlf {text.count(chr(13) + chr(10))}')

    ast.parse(open(__file__, encoding='utf-8').read())
    print('AST OK')


if __name__ == '__main__':
    sys.exit(main())