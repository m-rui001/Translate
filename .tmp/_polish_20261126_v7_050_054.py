def cjk(s):
    return sum(1 for ch in s if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for chunk in ('chunk050', 'chunk052', 'chunk053', 'chunk054'):
        d = os.path.join(ROOT, chunk)
        path = os.path.join(d, 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        with open(os.path.join(d, BAK), encoding='utf-8', newline='') as f:
            before = f.read()
        lines_before = before.count('\n') + 1
        cjk_before = cjk(before)
        n = 0
        for cat, old, new, why in EDITS[chunk]:
            assert text.count(old) == 1, (chunk, cat, old[:24], text.count(old))
            text = text.replace(old, new)
            n += 1
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        lines_after = text.count('\n') + 1
        assert lines_after == lines_before, (chunk, lines_before, lines_after)
        assert text.count('\r\n') == before.count('\r\n'), chunk
