def cjk(s):
    return sum(1 for ch in s if '\u4e00' <= ch <= '\u9fff')


def main():
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, 'chunk' + chunk)
        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copy2(f, b)
        with open(f, encoding='utf-8', newline='') as fh:
            text = fh.read()
        old_cjk = cjk(text)
        old_lines = len(text.replace('\r\n', '\n').split('\n'))
        n = 0
        for cat, old, new, why in edits:
            assert old in text, (chunk, 'MISSING', old[:30])
            assert text.count(old) == 1, (chunk, 'NOT-UNIQUE', old[:30])
            text = text.replace(old, new)
            n += 1
        with open(f, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        new_lines = len(text.replace('\r\n', '\n').split('\n'))
        assert old_lines == new_lines, (chunk, old_lines, new_lines)
        assert text.count('“') == text.count('”'), (chunk, text.count('“'), text.count('”'))
        assert '"' not in text, (chunk, 'ascii quote')
        print('chunk%s: 改动 %d 条 | 行数 %d -> %d | 汉字 %d -> %d | 引号 %d/%d'
              % (chunk, n, old_lines, new_lines, old_cjk, cjk(text),
                 text.count('“'), text.count('”')))


main()
