def load(key):
    p = os.path.join(BASE, key + '_zh.json')
    raw = open(p, 'rb').read().decode('utf-8')
    return p, json.loads(raw), ('\r\n' if '\r\n' in raw else '\n')


def apply(key):
    p, d, nl = load(key)
    bak = json.load(open(p + '.bak_20261126', encoding='utf-8'))
    n0 = len(d)
    assert len(d) == len(bak), key
    hits = 0
    for old, new in EDITS[key]:
        idx = [i for i, s in enumerate(d) if old in s]
        assert len(idx) == 1, (key, old[:20], idx)
        i = idx[0]
        assert d[i].count(old) == 1, (key, old[:20], d[i].count(old))
        d[i] = d[i].replace(old, new)
        hits += 1
    assert len(d) == n0
    with io.open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(json.dumps(d, ensure_ascii=False, indent=1).replace('\n', nl))
    # 自检
    d2 = json.load(open(p, encoding='utf-8'))
    assert len(d2) == n0
    assert all(x.strip() for x in d2), 'empty para'
    for s in d2:
        assert '"' not in s, ('ascii quote', s[:30])
        for bad in ('。。', '，，', '、、', '；；', '：：'):
            assert bad not in s, (bad, s[:30])
        assert '  ' not in s, ('double space', s[:30])
        assert s == s.strip(), ('edge space', s[:30])
    print('%-10s 段数 %d（改前 %d）  改动 %d 条  换行 %s'
          % (key, len(d2), n0, hits, 'CRLF' if nl == '\r\n' else 'LF'))
    return hits


def main():
    tot = 0
    for k in ('tg_dawn', 'tg_dreams', 'tg_honour'):
        tot += apply(k)
    print('合计改动 %d 条；脚本自检：' % tot, end=' ')
    ast.parse(open(__file__, encoding='utf-8').read())
    print('ast.parse OK')


