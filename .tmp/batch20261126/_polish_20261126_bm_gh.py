def load(key):
    path = os.path.join(HERE, key + "_zh.json")
    with open(path, encoding="utf-8", newline="") as f:
        return path, json.load(f)


def save(path, data):
    with open(path, "w", encoding="utf-8", newline="") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")


def apply(key, edits):
    path, d = load(key)
    before = len(d)
    n = 0
    for idx, old, new in edits:
        if idx is None:  # 全篇归一
            total = sum(p.count(old) for p in d)
            assert total == 10, (key, old, total)
            for i, p in enumerate(d):
                d[i] = p.replace(old, new)
            n += total
            continue
        assert old in d[idx], (key, idx, old[:24])
        assert d[idx].count(old) == 1, (key, idx, old[:24])
        d[idx] = d[idx].replace(old, new)
        n += 1
    assert len(d) == before
    save(path, d)
    return n, before


def selfcheck(key):
    path, d = load(key)
    with open(path, encoding="utf-8", newline="") as f:
        raw = f.read()
    bak = path + ".bak_20261126"
    with open(bak, encoding="utf-8", newline="") as f:
        d0 = json.load(f)
    assert len(d) == len(d0), "段数变了"
    assert all(p.strip() for p in d), "有空段"
    assert not any('"' in p for p in d), "有 ASCII 直引号"
    assert '\\"' not in raw, "有 ASCII 直引号"
    for bad in ("。。", "，，", "、、", "……。", "！！"):
        assert bad not in "".join(d), bad
    han = sum(1 for p in d for ch in p if "\u4e00" <= ch <= "\u9fff")
    crlf = raw.count("\r\n")
    diff = [i for i in range(len(d)) if d[i] != d0[i]]
    print("%s: 段数 %d（备份同） 汉字 %d 换行 %s 改动段 %d"
          % (key, len(d), han, "CRLF" if crlf else "LF", len(diff)))
    return han, len(d), len(diff)


