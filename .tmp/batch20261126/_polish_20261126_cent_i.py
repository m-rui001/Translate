def main():
    if not os.path.exists(BAK):
        with open(P, 'rb') as f:
            raw = f.read()
        with open(BAK, 'wb') as f:
            f.write(raw)
        print('backup created:', os.path.basename(BAK))
    else:
        print('backup exists, kept:', os.path.basename(BAK))

    with open(P, 'r', encoding='utf-8', newline='') as f:
        txt = f.read()
    before = json.loads(txt)
    n_before = len(before)

    n = 0
    for old, new in EDITS:
        c = txt.count(old)
        assert c == 1, (c, old[:50])
        txt = txt.replace(old, new, 1)
        n += 1

    d = json.loads(txt)
    assert len(d) == n_before, ('array length changed', n_before, len(d))
    assert all(p.strip() for p in d), 'empty paragraph'
    assert '\r\n' in txt and txt.count('\r\n') == txt.count('\n'), 'newline style changed'

    # 自检：ASCII 直引号 / 重复标点 / 汉字夹英文
    import re
    for i, p in enumerate(d):
        assert '"' not in p, ('ascii quote', i)
        assert not re.search(r'[。！？，、；：]{2,}', p.replace('……', '')), ('dup punct', i)
        assert not re.search(r'[\u4e00-\u9fff] [a-z]', p), ('latin gap', i)
        assert '⟦' not in p, ('marker', i)

    with open(P, 'w', encoding='utf-8', newline='') as f:
        f.write(txt)

    print(f'cent_i: edits={n} paras={len(d)} (was {n_before}) ok')
    print('backup paras =', len(json.load(open(BAK, encoding='utf-8'))))
    ast.parse(open(__file__, encoding='utf-8').read())


main()