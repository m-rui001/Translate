def han_count(s):
    return len(re.findall(r"[\u4e00-\u9fff]", s))


def main():
    report = {}
    for key, (indent, edits) in EDITS.items():
        path = os.path.join(BASE, key + "_zh.json")
        with open(path, encoding="utf-8", newline="") as f:
            d = json.load(f)
        n0 = len(d)
        base = {}
        for idx, old, new in edits:
            base[idx] = base.get(idx, 1)

        # 逐条定位 → 断言 → 替换
        cur = {}
        applied = 0
        for idx, old, new in edits:
            text = cur.get(idx, d[idx])
            if old not in text and new in text:
                continue  # 已改过（重跑安全）
            assert old in text, "NOT FOUND %s[%d]: %r" % (key, idx, old[:30])
            assert text.count(old) == 1, "NOT UNIQUE %s[%d]: %r" % (key, idx, old[:30])
            text = text.replace(old, new, 1)
            assert new in text and old not in text
            cur[idx] = text
            applied += 1
        for idx, text in cur.items():
            d[idx] = text

        # 自检
        assert len(d) == n0, "段数变了"
        assert all(p.strip() for p in d), "出现空段"
        bad = []
        for i, p in enumerate(d):
            if '"' in p:
                bad.append((i, "ASCII 引号"))
            if re.search(r"[。，；：！？]{2,}", p) and "……" not in p:
                bad.append((i, "重复标点"))
            if re.search(r"[\u4e00-\u9fff] [a-z]|[a-z] [\u4e00-\u9fff]", p):
                bad.append((i, "残留英文"))
            if p[-1] not in "。！？…」”·）—：" and not p.endswith("\n"):
                bad.append((i, "段末无标点: " + p[-6:]))
        half = [(i, p.count("；——")) for i, p in enumerate(d) if "；——" in p]
        assert not bad, bad
        assert not half, half

        # 落盘：原 indent / LF
        with open(path, "w", encoding="utf-8", newline="") as f:
            json.dump(d, f, ensure_ascii=False, indent=indent)

        report[key] = {
            "段数": n0,
            "改前汉字": sum(han_count(p) for p in d),
            "改动": len(edits),
            "本次应用": applied,
            "涉及段": len(cur),
        }
        print("%-9s 段数=%d 改动=%d 本次应用=%d 涉及段=%d" %
              (key, n0, len(edits), applied, len(cur)))
    return report


