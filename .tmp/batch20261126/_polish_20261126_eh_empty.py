def main():
    with open(ZH, encoding='utf-8', newline='') as f:
        d = json.load(f)
    n_before = len(d)
    hits = 0
    for idx, old, new in EDITS:
        t = d[idx]
        assert old in t, 'MISS [%d]: %r' % (idx, old)
        assert t.count(old) == 1, 'AMBIG [%d]: %r' % (idx, old)
        d[idx] = t.replace(old, new)
        hits += 1
    assert len(d) == n_before
    # 自检
    for i, p in enumerate(d):
        assert isinstance(p, str) and p.strip(), 'EMPTY [%d]' % i
        assert '"' not in p, 'ASCII quote [%d]' % i
        for bad in ('。。', '，，', '、、', '；；', '：：'):
            assert bad not in p, 'dup punct %s [%d]' % (bad, i)
    with open(ZH, 'w', encoding='utf-8', newline='') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    # 回读校验
    with open(ZH, encoding='utf-8') as f:
        back = json.load(f)
    assert len(back) == n_before and back != []
    assert all(x.strip() for x in back)
    print('%s: 段数 %d → %d，改动 %d 条' % (KEY, n_before, len(back), hits))
    from collections import Counter
    print(Counter(CATS.values()))


main()
