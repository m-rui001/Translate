CNT = {}
for ck, pairs in EDITS.items():
    d = os.path.join(BASE, "chunk" + ck)
    fp = os.path.join(d, "final.txt")
    bak = fp + ".bak_20261125"
    if not os.path.exists(bak):
        shutil.copy2(fp, bak)
        print(ck, "备份新建")
    else:
        print(ck, "备份已存在，不覆盖")
    with open(fp, encoding="utf-8", newline="") as f:
        text = f.read()
    nl = "CRLF" if "\r\n" in text else "LF"
    lines_before = text.count("\n")
    han_before = sum(1 for ch in text if "\u4e00" <= ch <= "\u9fff")
    applied = 0
    for old, new in pairs:
        n = text.count(old)
        if n == 0 and new in text:
            print("  已应用，跳过：", new[:18])
            continue
        assert n == 1, (ck, old, n)
        text = text.replace(old, new)
        applied += 1
    lines_after = text.count("\n")
    han_after = sum(1 for ch in text if "\u4e00" <= ch <= "\u9fff")
    assert lines_before == lines_after, (ck, lines_before, lines_after)
    with open(fp, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    CNT[ck] = applied
    print("%s 改动 %d 条 | 行 %d=%d | 汉字 %d→%d | %s" %
          (ck, applied, lines_before, lines_after, han_before, han_after, nl))

print("合计", sum(CNT.values()), "条", CNT)
