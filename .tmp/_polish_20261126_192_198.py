HAN = re.compile(r"[\u4e00-\u9fff]")


def main():
    total = 0
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, "chunk" + chunk)
        path = os.path.join(d, "final.txt")
        bak = os.path.join(d, BAK)
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
            print(f"chunk{chunk}: 备份 -> {BAK}")
        else:
            print(f"chunk{chunk}: 备份已存在，未覆盖")

        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()

        han_before = len(HAN.findall(text))
        nl = "\r\n" if "\r\n" in text else "\n"
        lines_before = text.count(nl)
        paras_before = len([p for p in text.split(nl) if p.strip()])

        for old, new in edits:
            assert old in text, f"chunk{chunk} 未命中: {old[:30]}"
            assert text.count(old) == 1, f"chunk{chunk} 命中不唯一: {old[:30]}"
            text = text.replace(old, new)
            total += 1

        han_after = len(HAN.findall(text))
        lines_after = text.count(nl)
        paras_after = len([p for p in text.split(nl) if p.strip()])
        assert lines_before == lines_after, f"chunk{chunk} 行数变了"
        assert paras_before == paras_after, f"chunk{chunk} 段数变了"

        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print(f"chunk{chunk}: 改动 {len(edits)} 条 | 行数 {lines_before}->{lines_after} "
              f"| 段数 {paras_before}->{paras_after} | 汉字 {han_before}->{han_after} "
              f"| 换行 {'CRLF' if nl == chr(13) + chr(10) else 'LF'}")

    print("合计改动", total, "条")
    ast.parse(open(__file__, encoding="utf-8").read())
    print("ast.parse OK")


if __name__ == "__main__":
    main()