def han_count(s):
    return len(re.findall(r"[\u4e00-\u9fff]", s))


def main():
    report = []
    for chunk, edits in EDITS.items():
        d = os.path.join(BASE, chunk)
        path = os.path.join(d, "final.txt")
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
            print("备份新建: %s" % bak)
        else:
            print("备份已存在，未覆盖: %s" % bak)

        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before_lines = text.count("\r\n") + (0 if text.endswith("\r\n") else 1)
        before_han = han_count(text)
        before_paras = len(text.split("\r\n\r\n"))

        for old, new in edits:
            assert old in text, "[%s] 未命中: %s" % (chunk, old[:40])
            assert text.count(old) == 1, "[%s] 命中 %d 次: %s" % (
                chunk, text.count(old), old[:40])
            text = text.replace(old, new)

        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)

        after_lines = text.count("\r\n") + (0 if text.endswith("\r\n") else 1)
        after_han = han_count(text)
        after_paras = len(text.split("\r\n\r\n"))
        assert before_lines == after_lines, chunk
        assert before_paras == after_paras, chunk
        report.append((chunk, before_paras, before_lines, after_lines,
                       before_han, after_han, len(edits),
                       "CRLF" if "\r\n" in text else "LF"))
        print("%s: 段 %d→%d 行 %d→%d 汉字 %d→%d 改动 %d 条 %s" % (
            chunk, before_paras, after_paras, before_lines, after_lines,
            before_han, after_han, len(edits),
            "CRLF" if "\r\n" in text else "LF"))

    total = sum(r[6] for r in report)
    print("合计改动 %d 条" % total)


main()
