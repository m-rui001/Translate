HAN = re.compile(r"[\u4e00-\u9fff]")


def stats(text):
    lines = text.split("\r\n")
    paras = sum(1 for ln in lines if ln.strip())
    return len(lines), paras, len(HAN.findall(text))


def main():
    total = 0
    for chunk, edits in EDITS.items():
        path = os.path.join(BASE, "chunk" + chunk, "final.txt")
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        before = stats(text)
        n = 0
        for old, new in edits:
            assert old in text, "未命中：" + old[:40]
            assert text.count(old) == 1, "命中数不为 1：" + old[:40]
            text = text.replace(old, new)
            n += 1
        after = stats(text)
        assert after[0] == before[0], "行数变了"
        assert after[1] == before[1], "段数变了"
        assert text.count("\u201c") == text.count("\u201d"), "引号不成对"
        assert '"' not in text, "出现半角引号"
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print("chunk%s 改动 %d 条 | 行数 %d→%d | 段数 %d→%d | 汉字 %d→%d"
              % (chunk, n, before[0], after[0], before[1], after[1],
                 before[2], after[2]))
        total += n
    print("合计改动 %d 条" % total)


main()
