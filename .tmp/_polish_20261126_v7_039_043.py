def main():
    total = 0
    for key in ["039", "041", "042", "043"]:
        d = os.path.join(BASE, "chunk" + key)
        fp = os.path.join(d, "final.txt")
        bak = fp + ".bak_20261125"
        if not os.path.exists(bak):
            shutil.copy2(fp, bak)
        if FROM_BAK:  # 每次从备份重跑，结果可复现
            shutil.copy2(bak, fp)
        with open(fp, encoding="utf-8", newline="") as f:
            text = f.read()
        before_lines = text.count("\n")
        before_han = sum(1 for ch in text if "\u4e00" <= ch <= "\u9fff")
        n = 0
        for old, new in EDITS[key]:
            assert old in text, "MISS %s: %s" % (key, old[:40])
            assert text.count(old) == 1, "DUP %s: %s" % (key, old[:40])
            text = text.replace(old, new)
            n += 1
        with open(fp, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        after_lines = text.count("\n")
        after_han = sum(1 for ch in text if "\u4e00" <= ch <= "\u9fff")
        assert before_lines == after_lines, "LINE CHANGED %s" % key
        fr = json.load(open(os.path.join(ROOT, "chunks", VOL, "chunk%s.json" % key),
                            encoding="utf-8"))
        paras = [p for p in text.replace("\r\n", "\n").split("\n") if p.strip()]
        assert len(paras) == len(fr), "PARA COUNT %s: %d vs %d" % (key, len(paras), len(fr))
        assert '"' not in text, "ASCII QUOTE %s" % key
        for pair in ("“”", "‘’", "「」"):
            pass
        nl = "CRLF" if "\r\n" in text else "LF"
        print("chunk%s  行数 %d -> %d  汉字 %d -> %d  改动 %d 条  换行 %s  段数 %d"
              % (key, before_lines, after_lines, before_han, after_han, n, nl, len(paras)))
        total += n
    print("合计改动 %d 条" % total)


main()
