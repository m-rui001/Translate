def main():
    report = []
    for chunk, edits in EDITS.items():
        d = os.path.join(V4, chunk)
        path = os.path.join(d, 'final.txt')
        bak = os.path.join(d, BAK)
        if not os.path.exists(bak):
            shutil.copyfile(path, bak)
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        before_lines = len(text.replace('\r\n', '\n').split('\n'))
        before_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        n = 0
        for old, new in edits:
            assert old in text, (chunk, old[:40])
            assert text.count(old) == 1, (chunk, text.count(old), old[:40])
            text = text.replace(old, new)
            n += 1
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        after_lines = len(text.replace('\r\n', '\n').split('\n'))
        after_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        assert before_lines == after_lines, (chunk, before_lines, after_lines)
        report.append((chunk, n, before_lines, after_lines, before_cjk, after_cjk,
                       'CRLF' if '\r\n' in text else 'LF'))
        print(f'{chunk}: 改动 {n} 条 | 行数 {before_lines}->{after_lines} | '
              f'汉字 {before_cjk}->{after_cjk} | {"CRLF" if chr(13) + chr(10) in text else "LF"}')
    print('total edits', sum(r[1] for r in report))


main()
