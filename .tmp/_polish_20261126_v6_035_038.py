def cjk(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main():
    total = 0
    only = sys.argv[1:]
    for chunk, edits in EDITS.items():
        if only and chunk not in only:
            continue
        d = os.path.join(BASE, chunk)
        path = os.path.join(d, "final.txt")
        bak = os.path.join(d, "final.txt.bak_20261125")
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
            print("%s 备份已建 %s" % (chunk, os.path.basename(bak)))
        else:
            print("%s 备份已存在，不覆盖" % chunk)

        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        crlf = "\r\n" in text
        before_cjk = cjk(text)
        before_lines = len(text.splitlines())

        if not any(old in text for cat, old, new, why in edits):
            print("%s 已润过，跳过（无一条 old 命中）" % chunk)
            continue

        for i, (cat, old, new, why) in enumerate(edits, 1):
            assert old in text, "%s #%d 未命中: %s" % (chunk, i, old[:40])
            assert text.count(old) == 1, "%s #%d 命中 %d 次: %s" % (
                chunk, i, text.count(old), old[:40])
            text = text.replace(old, new, 1)

        after_lines = len(text.splitlines())
        assert before_lines == after_lines, "%s 行数变了" % chunk
        assert ("\r\n" in text) == crlf, "%s 换行符变了" % chunk

        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        total += len(edits)
        print("%s: 改动 %d 条 | 行 %d=%d | 汉字 %d->%d | %s" % (
            chunk, len(edits), before_lines, after_lines, before_cjk, cjk(text),
            "CRLF" if crlf else "LF"))
    print("合计改动 %d 条" % total)


if __name__ == "__main__":
    main()

