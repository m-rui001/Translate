        f = os.path.join(d, 'final.txt')
        b = os.path.join(d, BAK)
        if not os.path.exists(b):
            shutil.copyfile(f, b)
        src = b if FROM_BAK else f
        with open(src, encoding='utf-8', newline='') as fh:
            text = fh.read()
        before_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        before_lines = text.replace('\r\n', '\n').count('\n')
        n = 0
        for old, new in EDITS[chunk]:
            assert old in text, (chunk, old[:30])
            assert text.count(old) == 1, (chunk, text.count(old), old[:30])
            text = text.replace(old, new)
            n += 1
        with open(f, encoding='utf-8', newline='') as fh:
            pass
        with open(f, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        after_cjk = sum(1 for ch in text if '\u4e00' <= ch <= '\u9fff')
        after_lines = text.replace('\r\n', '\n').count('\n')
        assert before_lines == after_lines, (chunk, before_lines, after_lines)
        paras = len([x for x in text.replace('\r\n', '\n').split('\n') if x.strip()])
        assert text.count('“') == text.count('”'), chunk
        assert '"' not in text, chunk
