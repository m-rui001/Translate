CHUNKS = ['009', '010', '011', '014', '016']


def hanzi(s):
    return sum(1 for ch in s if '\u4e00' <= ch <= '\u9fff')


def main():
    total = 0
    for c in CHUNKS:
        path = os.path.join(BASE, 'chunk' + c, 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        nl = 'CRLF' if '\r\n' in text else 'LF'
        par_before = len(text.replace('\r\n', '\n').split('\n\n'))
        hz_before = hanzi(text)
        n = 0
        for old, new in EDITS[c]:
            cnt = text.count(old)
            assert cnt == 1, (c, cnt, old[:30])
            text = text.replace(old, new)
            n += 1
        par_after = len(text.replace('\r\n', '\n').split('\n\n'))
        hz_after = hanzi(text)
        assert par_before == par_after, (c, par_before, par_after)
        assert '\n\n\n' not in text.replace('\r\n', '\n'), c
        print('chunk%s: %d 处 | 段数 %d=%d | 汉字 %d→%d | %s'
              % (c, n, par_before, par_after, hz_before, hz_after, nl))
        total += n
        if not DRY:
            for suffix in ('.bak_20261125', '.bak_20261126'):
                bak = path + suffix
                if not os.path.exists(bak):
                    shutil.copy2(path, bak)
            with open(path, 'w', encoding='utf-8', newline='') as f:
                f.write(text)
    print('合计 %d 处%s' % (total, '（dry run，未落盘）' if DRY else ''))


if __name__ == '__main__':
    main()
