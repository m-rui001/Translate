def main(only=None):
    total = 0
    for rel, pairs in JOBS:
        if only and rel not in only:
            continue
        p = os.path.join(OUT, rel.replace('/', os.sep), 'final.txt')
        with open(p, encoding='utf-8', newline='') as f:
            text = f.read()
        before = (text.count('\n') + 1, len([x for x in text.replace('\r\n', '\n').split('\n') if x.strip()]),
                  text.count('\r\n'))
        for old, new in pairs:
            assert old in text, (rel, old)
            assert text.count(old) == 1, (rel, old, text.count(old))
            text = text.replace(old, new)
        after = (text.count('\n') + 1, len([x for x in text.replace('\r\n', '\n').split('\n') if x.strip()]),
                 text.count('\r\n'))
        assert before == after, (rel, before, after)
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        print(f'{rel}: {len(pairs)} 处改动；行 {before[0]}→{after[0]}，非空段 {before[1]}→{after[1]}，'
              f'CRLF {before[2]}→{after[2]}')
        total += len(pairs)
    print(f'合计 {total} 处')


