def han(s):
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def main(edits_map=None):
    for chunk, edits in (edits_map or EDITS).items():
        path = os.path.join(BASE, "chunk" + chunk, "final.txt")
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        bak = path + ".bak_20261125"
        if not os.path.exists(bak):
            with open(bak, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            print(chunk, "备份已建", os.path.basename(bak))
        else:
            print(chunk, "备份已存在（未覆盖）")

        old_lines = text.split("\n")
        n_han_before = han(text)
        done = 0
        for old, new in edits:
            assert text.count(old) == 1, (chunk, old[:30], text.count(old))
            text = text.replace(old, new)
            done += 1
        new_lines = text.split("\n")
        assert len(old_lines) == len(new_lines), (chunk, len(old_lines), len(new_lines))
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        nl = "CRLF" if "\r\n" in text else "LF"
        print(f"{chunk}: 改动 {done} 条 | 行数 {len(old_lines)} -> {len(new_lines)} | "
              f"汉字 {n_han_before} -> {han(text)} | {nl}")


