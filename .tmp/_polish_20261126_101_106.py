def main():
    total = 0
    for num, edits in EDITS.items():
        d = BASE / ("chunk%03d" % num)
        f = d / "final.txt"
        bak = d / "final.txt.bak_20261125"
        text = open(f, encoding="utf-8", newline="").read()
        crlf = "\r\n" in text
        before_han = han(text)
        before_lines = text.count("\n")
        if not bak.exists():
            shutil.copy2(f, bak)
            print("bak 新建 %s" % bak.name)
        else:
            print("bak 已存在，未覆盖 %s" % bak.name)
        n = 0
        for old, new, cat, why in edits:
            if old not in text and new in text:
                print("  已应用，跳过：%s…" % old[:16])
                continue
            assert old in text, ("未命中", num, old)
            assert text.count(old) == 1, ("非唯一", num, old, text.count(old))
            text = text.replace(old, new, 1)
            n += 1
        open(f, "w", encoding="utf-8", newline="").write(text)
        total += n
        print("chunk%03d  改动 %2d 条  行数 %d→%d  汉字 %d→%d  换行 %s"
              % (num, n, before_lines, text.count("\n"), before_han, han(text),
                 "CRLF" if crlf else "LF"))
    print("合计 %d 条" % total)


main()
