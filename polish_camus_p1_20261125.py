# 专名归一：神父 → 神甫（全书 canon：神甫 38 处）
NAME_NORM = {"c004": 4, "c059": 3, "c062": 11, "c063": 12}

n_fix = 0
for chunk, old, new, tag, why in FIXES:
    if tag == "x":
        continue
    path = os.path.join(OUT, chunk, "final.txt")
    bak = path + BAK
    if not os.path.exists(bak):
        shutil.copy2(path, bak)
    with open(path, encoding="utf-8", newline="") as fh:
        text = fh.read()
    if old not in text and new in text:
        print("skip(applied)", chunk, why[:20]); continue
    assert old in text, (chunk, old)
    assert text.count(old) == 1, (chunk, text.count(old), old)
    text = text.replace(old, new)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    n_fix += 1
    print("ok", chunk, tag, why[:28])

n_name = 0
for chunk, expect in NAME_NORM.items():
    path = os.path.join(OUT, chunk, "final.txt")
    with open(path, encoding="utf-8", newline="") as fh:
        text = fh.read()
    got = text.count("神父")
    assert got == expect, (chunk, got, expect)
    text = text.replace("神父", "神甫")
    assert text.count("神父") == 0
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    n_name += got
    print("name", chunk, got)

print("fixes", n_fix, "names", n_name)
