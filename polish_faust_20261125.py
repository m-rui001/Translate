def main():
    total = 0
    for key in sorted(EDITS):
        path = os.path.join(BASE, key, 'final.txt')
        txt = io.open(path, encoding='utf-8', newline='').read()
        bak = path + '.bak_20261125'
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        nl = '\r\n' if '\r\n' in txt else '\n'
        lines = txt.split(nl)
        n_before = len(lines)
        for (mode, lineno, a, b) in EDITS[key]:
            line = lines[lineno - 1]
            if mode == 'H':
                assert line.startswith(a), (key, lineno, line[:40], a[:40])
                newline = b + line[len(a):]
            else:
                assert a in line, (key, lineno, a)
                assert txt.count(a) == 1, (key, lineno, txt.count(a), a)
                newline = line.replace(a, b, 1)
            needle = line                     # 整行作唯一针
            assert txt.count(needle) == 1, (key, lineno, 'line not unique', needle[:40])
            idx = txt.index(needle)
            txt = txt[:idx] + newline + txt[idx + len(needle):]
            lines = txt.split(nl)
        out = txt
        assert len(out.split(nl)) == n_before, (key, 'line count changed')
        assert '"' not in out and '\u201c' in out or True
        assert out.count('"') == 0, (key, 'ascii quote')
        io.open(path, 'w', encoding='utf-8', newline='').write(out)
        total += len(EDITS[key])
        print(key, len(EDITS[key]))
    print('TOTAL', total)


main()
