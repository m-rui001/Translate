touched = []
for (ch, sub), ops in sorted(OPS.items()):
    path = os.path.join(OUT, ch, sub, 'final.txt')
    with open(path, encoding='utf-8', newline='') as f:
        text = f.read()
    new = text
    n_file = 0
    for old, rep, is_re in ops:
        if is_re:
            got = len(re.findall(old, new))
            if not got:
                continue
            new = re.sub(old, rep, new)
        else:
            got = new.count(old)
            if not got:
                continue
            new = new.replace(old, rep)
        n_file += got
    if not n_file:
        continue
    assert new.count('\n') == text.count('\n'), (ch, sub, '行数变了')
    assert len(new.split('\n')) == len(text.split('\n')), (ch, sub, '段数变了')
    bak = path + BAK
    if not os.path.exists(bak):
        shutil.copy2(path, bak)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(new)
    total += n_file
    touched.append(f'{ch}/{sub}\t{n_file}')

print('收敛复扫补改:', total)
