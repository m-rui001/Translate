def main():
    total = 0
    for book, subs in FIX.items():
        path = os.path.join("out", book + ".epub")
        if not os.path.exists(path):
            print("  missing", book)
            continue
        subs = sorted(subs, key=lambda p: -len(p[0]))
        tmp = path + ".tmp"
        counts = []
        with zipfile.ZipFile(path) as z, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as o:
            for it in z.infolist():
                data = z.read(it.filename)
                if it.filename.endswith((".xhtml", ".ncx", ".opf")):
                    s = data.decode("utf-8")
                    for old, new in subs:
                        k = s.count(old)
                        if k:
                            s = s.replace(old, new)
                            counts.append((old, new, k))
                    data = s.encode("utf-8")
                o.writestr(it, data)
        shutil.move(tmp, path)
        n = sum(c for _, _, c in counts)
        total += n
        print("  %-26s %4d  %s" % (book[:26], n, " ".join("%s→%s:%d" % c for c in counts)))
    print("total", total)


if __name__ == "__main__":
    main()
