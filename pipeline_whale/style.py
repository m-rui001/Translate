"""Style contract for the Chinese Moby-Dick (publication-grade literary prose).

Injected into every writing prompt. Moby-Dick is not a normal novel: it is
Shakespearean blank verse gone wild, a sermon, an encyclopaedia, a whaling manual
and a metaphysical tract stitched into one. The contract has to make a model
produce *that*, not smooth modern narrative prose.
"""

STYLE = """
【项目】把赫尔曼·麦尔维尔《白鲸》(Moby-Dick; or, The Whale, 1851) 英文原文译成中文，
目标是有出版水准的文学译本，与中文世界里最好的译本比肩。

【原文中的外文与标注】
- 原文若整句引用外文（西班牙文铭文、拉丁文、法文），译文照原文抄录该外文，不改写、不音译，
  随后照原样继续译下去；不要在这些词上加引号或注。
- 原文的编辑性星号 *（脚注标记、或 * * * 表示节略）不是正文内容：单个星号直接略去，
  连续的 * * * 处译作“……”以表示节略。

【三条准则，冲突时按此优先级】
1. 忠实：麦尔维尔说的是什么、说多少、按什么次序说、用什么语气说，全部保住。
   鲸类的解剖尺寸、绳索的走向、船的方位、圣经引文、数字与年代，一个都不能错、不能略。
2. 文学性：这是十九世纪美国散文的顶点，句子像圣经又像莎士比亚。译文必须有汉语的
   分量与气势：长短句的落差、排比的推力、破折号的喘息、古语的庄重、反讽的冷。
   不能是“信息正确但干瘪”的转述，也不能是圆滑的现代白话小说腔。
3. 可读性：中文读者要能读下去。可读性靠语序、断句、指代、标点解决，不靠删内容。

冲突时的取舍：
- 忠实优先于漂亮。不为顺口而合并句子、略去从句、弱化语气、抹平重复。
- 文学性优先于顺口。该拗口的地方（麦尔维尔故意堆叠的同位语、连缀的形容词、
  法庭文书般的重复）要保留其拗口，但必须让读者读得懂这拗在何处。
- 可读性只作用于断句与语序，不作用于删减。

一、文体与语感
1. 以现代汉语书面语为底，允许少量文言语汇入句（“遂”“乃”“其”“殊”“未尝”“无乃”），
   造成沉着的古意；但绝不写成文言，不用之乎者也，不堆四字格，不写“赋体”骈文。
2. 麦尔维尔的标志性节奏：一个短句立住，接着一个越滚越长的复合句压过来，
   最后用破折号一记顿住。译文必须复现这个呼吸：
   - 短句要短、要硬，能独立成句。
   - 长句要长，用逗号、分号、破折号连缀，不要在中文里切成四个同长的短句。
   - 破折号是麦尔维尔的第二个肺：插入、修正、突转、自嘲都用它，密度要接近原文。
3. 禁用翻译腔套式：“进行……的处理”“对于……而言”“使得……得以……”“作为一个……”
   “……的……的”层层套叠；少用“被”字句；少用“一个”“一种”这类量化垫字；
   避免“了”字连缀；避免“它是……的”式判断句堆叠。
4. 比喻、隐喻、通感一律按中文重新铸造，让它在汉语里成立，不要硬搬原文词面；
   但麦尔维尔把鲸比作教堂、把海洋比作命运这类大比喻，气势必须同等，不许降格为“好像”。
5. 打比方时的奇崛（鲸头是“斯芬克司”，鲸尾是“攻城槌”，抹香鲸脑袋是“海德堡大酒桶”）
   是全书的结构性玩笑，照译，不要解释，不要加注。

二、依文体的分腔（本书一大半的力量来自语体切换）
- 叙述（以实玛利第一人称）：见闻细密，情绪在自己的冷嘲与惊惧之间摆荡，偶尔突然庄严。
  前半部多口语与幽默，越往后越沉、越玄。
- 亚哈：莎士比亚式独白。感叹句、呼语、咒誓、倒装。多用“啊”“唷”“且看”“你这”，
  称呼星、火、雷、鲸为“你”。狂暴处音节要短促，冥想处长句要盘旋。
- 斯达巴克：教友派，语言朴素、克制、直的；他劝谏时用的是良心而非修辞。
- 斯塔布：乐天、油滑、爱开玩笑、随时叼烟斗；口语化，几乎俚俗，句子短而快。
- 弗拉斯克：粗莽、头脑简单、句子更短。
- 魁魁格：话极少，平静，带异教式的庄重与善意；“我跟你是一体了”这类话要朴素到底。
- 塔希蒂格、达格：几乎不说话，用动作与喊叫；译者不要替他们添台词。
- 皮普：落水之后疯掉的孩子的谵语，破碎、单薄、忽然又极深。
- 梅普尔神甫讲道：钦定本圣经腔。庄重、缓、层层加重，多用“船友们”“弟兄们”，
  引经文时用“经上说”“主说”，节奏要有教堂石壁的回声。
- 水手合唱、号子、歌谣：短行、押韵、可唱。
- 揭取鲸脂、解剖鲸骨、煮油等“工艺段落”：用精准的工艺术语，语气像百科全书或操作手册，
  冷、实、一步接一步，不要抒情，不要把它译成感想。
- 论证段落（第24章辩护人、第82章捕鲸的光荣、第89章有主鲸与无主鲸、第90章正面反面）：
  像律师的陈词，逻辑连接词要清楚（“因为”“既然”“然而”“据此”），句子要长而有推力。

三、圣经与古典引文
1. 凡引《圣经》，用中文通行的和合本措辞（如“上帝就造出大鱼”“耶和华安排一条大鱼
   吞了约拿”“你们要结出果子来，与悔改的心相称”），不加引号以外的说明。
2. 引出处的署名（如 Job. / Jonah. / Hackluyt.）照原文体例独立成行，译名照术语表。
3. 古典典故（珀耳修斯、安德洛墨达、伊克西翁、伽图）不加注释，直接译名。

四、忠实度细则
- 不漏译、不增译、不改情节。原文的重复、啰嗦、迟疑、自我打断要保留。
- 术语表所列专名严格照译，全书一致；船名一律加“号”，书名号内不加“号”。
- 度量与货币按原文保留，可用中文数字，必要时加“约”字。**全书只用一套写法**：
  长度呎、吋、浔、哩、里格，容量桶、加仑，货币几尼、镑、先令、便士。
  不要写成英尺/英寸/英里/海浬/噚——同一部书里两套单位混用是硬伤。
- 原文的斜体强调由 ⟦i⟧…⟦/i⟧ 标出，译文请用中文手段落实其强调（语序、虚词、“所谓”、
  强调性引号），并在译文中同样用 ⟦i⟧…⟦/i⟧ 保留这层标记。
- 分行的诗（verse 块）必须保持行数、分行与诗节结构，不得并成散文。
  戏剧对白（如第40章）保留“人物名：台词”的体例。
- 数字：正文里凡普通数量、年代、尺寸，一律写成中文数字（一八五一年、三百六十浬、
  十二呎），不用阿拉伯数字。
- 不用脚注、不用括号夹注补充原文没有的解释。

【坏例子 → 好例子（照此标准）】
- Call me Ishmael. ✗ 叫我以实玛利吧。 ✓ 叫我以实玛利。
- It is a way I have of driving off the spleen, and regulating the circulation.
  ✗ 这是我驱除坏脾气、调节血液循环的一种方式。
  ✓ 这是我驱散郁气、调理血脉的老法子。
- Why did the poor poet of Tennessee, upon suddenly receiving two handfuls of silver,
  deliberate whether to buy him a coat, which he sadly needed, or invest his money in
  a pedestrian excursion to the Rock of Abraham?
  ✗ 为什么田纳西的穷诗人突然收到两把银子时，会考虑是买一件他急需的外套，还是把钱
    投资到亚伯拉罕岩的徒步旅行中去？
  ✓ 田纳西那个穷诗人，忽然到手两把银币，为什么还要盘算半天：是买一件他实在少不得的
    外套呢，还是拿这笔钱去做一趟朝拜亚伯拉罕岩的徒步旅行？
- But no. Let us now glance at another ocean.
  ✗ 但是不。现在让我们看看另一个海洋。
  ✓ 可是不成。且让我们再看另一片海洋。
"""

