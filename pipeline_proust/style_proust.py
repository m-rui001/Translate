"""Style contract for Proust, reverse-engineered from Zhou Kexi's published prose.

Deliberately opposite to the LOTR brief: Proust's long, breathing sentences must
be preserved, not tidied into short Chinese clauses.
"""

STYLE = """
【项目】把马塞尔·普鲁斯特《追忆似水年华》法语原文译成中文。
这是补译工程：已有周克希先生的译本（第一卷《去斯万家那边》、第二卷《在少女花影下》、
第五卷《女囚》等），我们的译文必须与之无缝衔接——人名、地名、语气、句法节奏都须一致。

【最高准则】让中文读者以为这就是原生的普鲁斯特：一个句子可以在页面上延伸很久，
逗号连着逗号，从句套着从句，思绪拐了三道弯又回到起点。

一、句法（最重要）
1. **不要拆长句。** 普鲁斯特的句子就是他的呼吸。原文一个长句，中文就译成一个长句。
   允许超过 80 字、100 字甚至更长。拆成短句 = 毁掉这本书。
2. 保留从句的嵌套层次与推进顺序：状语→主句→补语→插入语→回补。
   不要把后置的补语提前，不要把插入语独立成句。
3. 逗号是普鲁斯特的节奏器：原文用逗号的地方中文就用逗号。
   句号只在原文确实用句号（.）的地方用。
4. 分号、破折号、冒号按原文功能对应：分号（;）保留分号，破折号（—）保留破折号。
5. 长句内部如果必须调整语序以合乎中文，也只做最小调整，保持"一口气读下去"的黏性。

二、语气与用词
1. 叙述者是"我"，语气温和、自省、带一点自嘲与耽溺，不夸张、不煽情。
2. 用词偏典雅但不文言：用"倘若""固然""于是""其实""毕竟""无非"这类虚词连接思绪，
   不用"的的的"套叠，不用"进行""对于""使得"等翻译腔。
3. 讽刺与幽默要留住：普鲁斯特的讽刺常裹在礼貌的长句里，不要软化成中性叙述。
4. 感官描写（气味、光线、触感、声音）要具体、绵密，这是全书的骨架。
5. 人物对话要带出阶层与教养的差别：贵族说话迂回、礼貌而带刺；布尔乔亚直白而笨拙。

三、专名与头衔
1. 人名、地名严格照术语表，与周克希先生的既有译文保持一致。
2. 法语贵族头衔保留：de → 德·，如 德·夏尔吕先生、德·盖尔芒特夫人、德·圣卢伯爵。
   不要译成"某某先生"就丢掉头衔。
3. 家族名（Guermantes、Guermantes 一族）用音译，不意译。
4. 作品名、乐曲名用《》：《追忆》《奏鸣曲》；小乐句（petite phrase）译「小乐句」。

四、标点与格式
1. 中文全角标点：，。；：？！“”‘’（）《》——……
2. 引号外层用“ ”，内层用‘ ’。
3. 段落与原文段落一一对应：可以调整句内语序，但不得合并或拆分段落。
4. 不加任何译注、说明、括号解释。
5. 数字、日期用中文读法；年份按原文保留。

五、忠实度
- 不漏译、不增译、不改情节。所有细节（家具、花木、光线方位、人物动作次序）必须保留。
- 普鲁斯特反复出现的意象与词语（玛德莱娜小蛋糕、山楂、小乐句、窗帘的光）
  要用同一译法反复出现，形成母题。
- 原文的重复、迟疑、自我修正、长篇大论的题外话，全部保留——那是他的意识流。
""".strip()

