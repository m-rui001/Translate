def stat(t):
    lines = t.split('\n')
    return len(lines), sum(1 for l in lines if l.strip() == '')


def main():
    touched = {}
    report = []
    for rel, mode, old, new, n in EDITS:
        path = os.path.join(OUT, rel.replace('/', os.sep), 'final.txt')
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
        if text.count(old) == 0 and text.count(new) >= 1:
            print('skip(already):', rel, old[:12])
            continue
        if mode == 'one':
            assert text.count(old) == 1 and n == 1, (rel, old, text.count(old))
        else:
            assert text.count(old) == n, (rel, old, text.count(old), n)
        assert new not in text or old == '那叫侍从卫士。', (rel, new)
        before = stat(text)
        text2 = text.replace(old, new)
        after = stat(text2)
        if rel != 'c019/c00':
            assert before == after, (rel, before, after)
        else:
            assert after[0] == before[0] - 1 and after[1] == before[1], (rel, before, after)
        # 备份（只做一次）
        if path not in touched:
            bak = path + '.bak_20261125'
            if not os.path.exists(bak):
                shutil.copy2(path, bak)
            touched[path] = before
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(text2)
        report.append((rel, old, new, n))

    print('files touched:', len(touched))
    total = 0
    for rel, old, new, n in report:
        total += n
        print('  %-10s %-18s -> %-16s x%d' % (rel, old[:18], new[:16], n))
    print('edits:', len(report), 'occurrences:', total)


main()

