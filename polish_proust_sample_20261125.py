def structure(text):
    lines = text.split('\n')
    return (len(lines), sum(1 for l in lines if not l.strip()))


done = []
for vol, chunk, old, new, kind, why in EDITS:
    f = f'{ROOT}/{vol}/{chunk}/final.txt'
    raw = open(f, encoding='utf-8', newline='').read()
    crlf = '\r\n' in raw
    text = raw.replace('\r\n', '\n') if crlf else raw
    assert old in text, (f, old)
    assert text.count(old) == 1, (f, old, text.count(old))
    before = structure(text)
    if not os.path.exists(f + BAK):
        shutil.copy2(f, f + BAK)
    text = text.replace(old, new)
    after = structure(text)
    assert before == after, (f, before, after)
    assert '⟦' not in text and '⟧' not in text
    open(f, 'w', encoding='utf-8', newline='').write(
        text.replace('\n', '\r\n') if crlf else text)
    done.append((vol, chunk, kind, why))

for d in done:
    print('%s/%s [%s] %s' % d)
print('润色改动:', len(done), '处')
