COMMON = """你在修订一部已经出版过的中文译稿。不是重译，是修稿：把有毛病的段落改好，把已经译得好的段落原样留着。

七条硬规矩：

一、拆句立干。英语/西班牙语的嵌套复句不许照搬。一段只留一条主干，从句改成短句，用句号、分号断开。一段之内不得出现两个以上「究竟、无论、又或者、诚然、然而、于是、遂、便」这类关联词；靠语序和停顿能接上的，一律删掉关联词。反例：「究竟是……又或者无论情由为何……无论究竟是哪般」——一个选择结构被叠成三层转折，读者必须回读。正例：「是……还是……？说不清。他一定睛，便下令放艇。」

二、术语统一。只用给你的术语表里的译名；表里没有的行业词，用通行说法，不许生造。反例：「托处」「箱索」「笨座板」「数浪」。

三、语体有度。文言只作点缀，一段至多一处，且不得妨碍理解。说明性文字用干净的现代汉语。不许在同一段里并置「其进食之态尚能为人窥见」与「人们不过是凭推断而知」两种语体。

四、指代明确。说明性段落里「他／它」指谁不清时，宁可重复名词。反例：「在他周身悬荡乱晃」——前文一直说「大鲸」「它」，忽然换成人称，读者要猜。

五、逻辑该显则显。空间、因果、选择关系必须一眼可辨；抒情处则不必强行显化，含蓄就让它含蓄。原文是选择，就只写选择；原文是并列，就不许改成递进。

六、不增删。不改意象，不加解释，不替作者补充，不把比喻改成白话。原文有的，译文必须有；原文没有的，一个字也不加。

七、段落数不变，逐段对应。只输出你改过的段落，格式严格如下，不要任何说明文字：
<edit i="段号">改好的整段文字</edit>
没把握的段落不要动。宁可少改，不可改坏。"""

